CREATE TABLE public.school_zone (
    school_zone_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    school_id VARCHAR(10) NULL,
    facility_type VARCHAR(100) NULL,
    facility_name VARCHAR(200) NULL,
    road_address VARCHAR(255) NULL,
    lot_address VARCHAR(255) NULL,
    management_agency VARCHAR(200) NULL,
    police_station VARCHAR(200) NULL,
    cctv_installed_yn BOOLEAN NULL,
    cctv_count INTEGER NULL,
    road_width VARCHAR(100) NULL,
    data_reference_date DATE NULL,
    geom geometry(Point, 5186) NOT NULL,
    loaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT school_zone_pkey PRIMARY KEY (school_zone_id),
    CONSTRAINT school_zone_school_fkey
        FOREIGN KEY (school_id) REFERENCES public.school (school_id)
);

CREATE INDEX idx_school_zone_geom
    ON public.school_zone USING GIST (geom);

CREATE INDEX idx_school_zone_school_id
    ON public.school_zone (school_id);
